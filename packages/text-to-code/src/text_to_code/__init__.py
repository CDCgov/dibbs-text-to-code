def text_to_code(eicr: str, schematron_report: str) -> TTCAugmenterInput:
    eicr_processor = EicrProcessor(eicr)
    data_fields = get_data_fields_from_schematron_error(schematron_report)

    augmentations: list[TTCAugmentation] = []

    for field_type, xpaths in data_fields.items():
        for xpath in xpaths:
            candidates = eicr_processor.get_text_candidates(xpath, field_type)
            criteria = get_evaluation_criteria_for_data_field(field_type)

            selected = select_relevant_text(candidates=candidates, criteria=criteria)

            if not selected:
                continue

            embedded_code = embed(selected)  # noqa
            opensearch_result = _mock_opensearch_query()
            new_code = opensearch_result["hits"]["hits"][0]["_source"]["code"]
            new_display_name = opensearch_result["hits"]["hits"][0]["_source"]["description"]
            new_original_text = selected

            augmentations.append(
                TTCAugmentation(
                    location=xpath,
                    data_type=field_type,
                    code=new_code,
                    display_name=new_display_name,
                    original_text=new_original_text,
                )
            )

    return TTCAugmenterInput(eicr=eicr, augmentations=augmentations)
